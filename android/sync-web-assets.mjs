#!/usr/bin/env node
'use strict';

/* ════════════════════════════════════════════════════════════════════════════
   Pull the game across from the web project and prepare it for the app.

   The web version in the parent folder stays the source of truth. This script
   copies it in, applies the one change the app needs, and mirrors the result
   into the native project. Run it after any edit to the web game and the app
   picks the change up:

       node sync-web-assets.mjs

   The one change: on the web, the game and the leaderboard API share an origin,
   so fetch('/api/get-scores') resolves correctly. In the app it does not —
   Capacitor serves the game from https://localhost, so that same path would ask
   the app for its own bundled files and never reach Vercel. So every API call
   gets prefixed with window.REZZY_API_BASE, which config.js sets.

   The patch is idempotent: running twice is harmless.
   ════════════════════════════════════════════════════════════════════════════ */

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const WEB  = resolve(HERE, '..');
const WWW  = join(HERE, 'www');
const NATIVE_ASSETS = join(HERE, 'android', 'app', 'src', 'main', 'assets', 'public');

const API_BASE = 'https://acalan-rezzy.vercel.app';

const FILES = ['index.html', 'game.js', 'style.css'];
const DIRS  = ['RezzySpriteSheet', 'Items', 'backgroundloop', 'font'];

function die(msg) {
    console.error('\n  ✗ ' + msg + '\n');
    process.exit(1);
}

// ── Sanity: are we actually next to the web game? ───────────────────────────
for (const f of FILES) {
    if (!existsSync(join(WEB, f))) {
        die(`Could not find ${f} in ${WEB}\n    This folder must sit directly inside the web project.`);
    }
}

// ── Copy ────────────────────────────────────────────────────────────────────
rmSync(WWW, { recursive: true, force: true });
mkdirSync(WWW, { recursive: true });

for (const f of FILES) cpSync(join(WEB, f), join(WWW, f));
for (const d of DIRS) {
    if (existsSync(join(WEB, d))) cpSync(join(WEB, d), join(WWW, d), { recursive: true });
    else console.warn(`  ! ${d}/ not found in the web project, skipping`);
}
console.log('  ✓ copied the game from ' + WEB);

// ── config.js: the only file the app adds ───────────────────────────────────
writeFileSync(join(WWW, 'config.js'),
`'use strict';

/* Where the leaderboard lives.

   Generated by sync-web-assets.mjs — edit API_BASE in that script, not here,
   or your change will be overwritten on the next sync. */

window.REZZY_API_BASE = ${JSON.stringify(API_BASE)};
`);
console.log('  ✓ wrote config.js  ->  ' + API_BASE);

// ── Patch game.js to route through the base URL ─────────────────────────────
{
    const p = join(WWW, 'game.js');
    let s = readFileSync(p, 'utf8');

    if (s.includes('const API_BASE')) {
        console.log('  · game.js already carries API_BASE, leaving it alone');
    } else {
        const edits = [
            ["'use strict';\n",
             "'use strict';\n\n" +
             "// Prefix for leaderboard calls. Empty in the browser, where the API is\n" +
             "// same-origin; set by config.js in the Android app, where the game is\n" +
             "// served from localhost and a bare '/api/...' would go nowhere.\n" +
             "const API_BASE = (typeof window !== 'undefined' && window.REZZY_API_BASE) || '';\n"],
            ["await fetch('/api/submit-score', {",
             "await fetch(API_BASE + '/api/submit-score', {"],
            ["const url = fresh ? '/api/get-scores?t=' + Date.now() : '/api/get-scores';",
             "const url = API_BASE + (fresh ? '/api/get-scores?t=' + Date.now() : '/api/get-scores');"],
        ];
        for (const [from, to] of edits) {
            const n = s.split(from).length - 1;
            if (n !== 1) {
                die(`game.js: expected exactly one match for\n      ${from.trim().slice(0, 70)}\n    but found ${n}.` +
                    `\n    The web game changed shape — update the edits in sync-web-assets.mjs.`);
            }
            s = s.replace(from, to);
        }
        writeFileSync(p, s);
        console.log('  ✓ patched game.js to use API_BASE');
    }
}

// ── config.js must load before game.js ──────────────────────────────────────
{
    const p = join(WWW, 'index.html');
    let h = readFileSync(p, 'utf8');
    if (h.includes('config.js')) {
        console.log('  · index.html already loads config.js');
    } else {
        const m = h.match(/[ \t]*<script src="game\.js[^"]*"><\/script>/);
        if (!m) die('index.html: could not find the game.js script tag.');
        h = h.replace(m[0], '    <script src="config.js"></script>\n' + m[0]);
        writeFileSync(p, h);
        console.log('  ✓ index.html now loads config.js first');
    }
}

// ── Mirror into the native project so Android Studio can build straight away ─
rmSync(NATIVE_ASSETS, { recursive: true, force: true });
mkdirSync(NATIVE_ASSETS, { recursive: true });
cpSync(WWW, NATIVE_ASSETS, { recursive: true });
console.log('  ✓ mirrored into android/app/src/main/assets/public');

console.log('\n  Done. Open the android/ folder in Android Studio and press Run.\n');
